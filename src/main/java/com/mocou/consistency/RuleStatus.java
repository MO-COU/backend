package com.mocou.consistency;

/**
 * 규칙 하나의 실행 상태.
 *
 * <p>검사한 결과 위반이 0건인 것과, 규칙이 죽어서 아무것도 못 본 것은 다르다. 이를 구분하지 않으면 규칙이 통째로 깨진 실행이 통과로 보인다.
 *
 * <p>{@code checked_count = 0}으로 판별할 수는 없다. 데이터가 비어 있어 검사 대상이 하나도 없는 정상 실행과 값이 같아지기
 * 때문이다.
 */
public enum RuleStatus {

    /** 규칙이 끝까지 실행됐다. 위반 유무는 별개다. */
    CHECKED,

    /** 규칙이 실행 중 실패해 판정하지 못했다. */
    FAILED
}
